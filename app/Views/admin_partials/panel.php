                            <div class="tab-pane fade show active" id="v-pills-home-nobd-3" role="tabpanel" aria-labelledby="v-pills-home-tab-nobd-3">
                                <ul>
                                    <li class="mb-2">The National Bureau of Investigation (NBI) saw its inception on November 13, 1936 upon approval of Commonwealth Act No. 181 by the legislature. It was the the brainchild of the late President Manuel L. Quezon and Jose A. Yulo, then Secretary of Justice.</li>
                                    <li class="mb-2">Tasked with organizing a Division of Investigation or DI patterned after the United States Federal Bureau of Investigation were Thomas Dugan, a veteran American police captain from the New York Police Department and Flaviano C. Guerrero, the only Filipino member of the United States Federal Bureau of Investigation.</li>
                                </ul>
                            </div>
                            <div class="tab-pane fade" id="v-pills-profile-nobd-3" role="tabpanel" aria-labelledby="v-pills-profile-tab-nobd-3">
                                <ul>
                                    <li class="mb-2">Undertakes the detection and investigation of crimes against Philippine laws, both on its own initiative or when public interest requires.</li>
                                    <li class="mb-2">Primary Jurisdiction: They have the "first right" to investigate specific major crimes, including:
                                        <ul>
                                            <li class="mt-2 mb-2"><strong>Cybercrime:</strong> Violations of the Cybercrime Prevention Act (RA 10175).</li>
                                            <li class="mb-2"><strong>Human Trafficking:</strong> Specifically in airports and transnational cases.</li>
                                            <li class="mb-2"><strong>Public Corruption:</strong> High-level graft and cases referred by the Inter-Agency Anti-Graft Coordinating Council.</li>
                                            <li class="mb-2"><strong>Extrajudicial Killings:</strong> Targeted attacks against media practitioners and activists.</li>
                                            <li class="mb-2"><strong>White-Collar Crimes:</strong> Large-scale fraud, commercial, and economic crimes.</li>
                                        </ul>
                                    </li>
                                    <li class="mb-2">Acts as the central repository for criminal and derogatory records (this is why you need an NBI Clearance for jobs or travel).</li>
                                    <li class="mb-2">Provides forensic and scientific expertise (DNA, ballistics, polygraphy) to other law enforcement agencies and the courts.</li>
                                    <li class="mb-2">NBI officers (from Regional Director rank up) have the legal authority to issue subpoenas to compel witnesses to appear or produce documents.</li>
                                    <li class="mb-2">Acts as the Interpol National Central Bureau for the Philippines, handling extradition and mutual legal assistance.</li>
                                </ul>
                            </div>
