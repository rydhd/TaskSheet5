                                    <li class="mb-2">The scale symbolizes equality and justice, while the sword represents authority and the power to enforce justice.
                                    </li>
                                    <li class="mb-2">Superimposed beneath the scale and sword, it signifies the nation’s sovereignty and the DOJ’s responsibility to uphold justice within the country. Latin motto "Justitiae Pax Opus": Translated as "Justice for All", this phrase underscores the DOJ’s foundational purpose and commitment to equitable legal protection.
