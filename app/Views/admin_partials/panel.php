                            <div class="tab-pane fade show active" id="v-pills-home-nobd-4" role="tabpanel" aria-labelledby="v-pills-home-tab-nobd-4">
                                <ul>
                                    <li class="mb-2">The National Privacy Commission is the country’s privacy watchdog; an independent body mandated to administer and implement the Data Privacy Act of 2012 and to monitor and ensure compliance of the country with international standards set for data protection.</li>
                                </ul>
                            </div>
                            <div class="tab-pane fade" id="v-pills-profile-nobd-4" role="tabpanel" aria-labelledby="v-pills-profile-tab-nobd-4">
                                <ul>
                                    <li class="mb-2">Formulating guidelines and regulations (like the Privacy-by-Design approach) to ensure organizations handle data ethically.</li>
                                    <li class="mb-2">Managing the NPCRS (NPC Registration System), where all companies (PICs) and processors (PIPs) must register their Data Protection Officers (DPOs) and data processing systems.</li>
                                    <li class="mb-2">Receiving complaints from "data subjects" (you) and investigating data privacy violations. They can issue Cease and Desist Orders or award indemnity (compensation) to victims.</li>
                                    <li class="mb-2">Operating the DBNMS (Data Breach Notification Management System), which requires organizations to report personal data breaches within 72 hours.</li>
                                    <li class="mb-2">Ensuring Filipinos know their 8 basic rights, such as the Right to be Informed, Right to Access, and Right to be Forgotten (Erasure).</li>
                                    <li class="mb-2">Coordinating with global privacy bodies (like the Global Privacy Assembly) to ensure cross-border data transfers are secure.</li>
                                </ul>
                            </div>
                            <div class="tab-pane fade" id="v-pills-logo-nobd-4" role="tabpanel" aria-labelledby="v-pills-logo-tab-nobd-4">
                                <ul>
                                    <li class="mb-2">The "P" is formed in a way that resembles a checkmark. This signifies compliance, verification, and validity, representing the NPC’s role in ensuring that organizations are "checked" and compliant with the Data Privacy Act (DPA) of 2012.</li>
                                    <li class="mb-2">The overall structure of the "P" also subtly mimics a shield, symbolizing the protection of personal data and the safeguarding of data subjects' rights against breaches and unauthorized use.</li>
                                    <li class="mb-2">The keyhole signifies that an organization has "unlocked" its compliance by registering its Data Protection Officer (DPO) and Data Processing Systems (DPS) with the NPC. It serves as a visual badge of trust for the public.</li>
                                    <li class="mb-2">The circle symbolizes a holistic and unified approach to data protection across all sectors of society.</li>
                                </ul>
