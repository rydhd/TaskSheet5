                            <div class="tab-pane fade show active" id="v-pills-home-nobd-2" role="tabpanel" aria-labelledby="v-pills-home-tab-nobd-2">
                                <ul>
                                    <li class="mb-2">The Department of Justice (DOJ) derives its mandate primarily from the Administrative Code of 1987 (Executive Order No. 292). It carries out this mandate through the Department Proper and the Department's attached agencies under the direct control and supervision of the Secretary of Justice.</li>
                                    <li class="mb-2">Under Executive Order (EO) 292, the DOJ is the government's principal law agency. As such, the DOJ serves as the government's prosecution arm and administers the government's criminal justice system by investigating crimes, prosecuting offenders and overseeing the correctional system.</li>
                                </ul>
                            </div>
                            <div class="tab-pane fade" id="v-pills-profile-nobd-2" role="tabpanel" aria-labelledby="v-pills-profile-tab-nobd-2">
                                <ul>
                                    <li class="mb-2">Investigates crimes, prosecutes offenders, and oversees the correctional system.</li>
                                    <li class="mb-2">Acts as the legal representative of the Republic of the Philippines, its agencies, and instrumentalities, including government-owned corporations, in all legal proceedings.</li>
                                    <li class="mb-2">Implements laws on the admission, stay, and naturalization of aliens through the Bureau of Immigration (BI), including processing refugee status applications.</li>
                                    <li class="mb-2">Through the Public Attorney’s Office (PAO), provides free legal services to indigent and qualified individuals in criminal, civil, labor, and administrative cases.</li>
                                    <li class="mb-2">Serves as the central authority for extradition and mutual legal assistance treaties (MLAT), and participates in international legal negotiations.</li>
                                    <li class="mb-2">Promotes conciliation and mediation through the Office for Alternative Dispute Resolution (OADR) to reduce court backlogs.</li>
                                    <li class="mb-2">Implements laws related to anti-money laundering, anti-trafficking, human rights protection, and victims’ compensation, among others.</li>
                                </ul>
                            </div>
                            <div class="tab-pane fade" id="v-pills-logo-nobd-2" role="tabpanel" aria-labelledby="v-pills-logo-tab-nobd-2">
